// The pack catalogue as SQL (docs/11): idempotent inserts of the repository's packs (templates/packs/*.json, the
// first-sheet template and the wizard starts) for a hosted project, where the seed does not run. A version is
// written once (`on conflict do nothing`): change a pack, raise its version. Run it after the migrations and after
// scripts/frameworks-sql.ts (a pack may build on a framework's library), as the database owner:
//   pnpm exec tsx scripts/packs-sql.ts > packs-catalogue.sql
import { repoPacks } from '../src/lib/packs/catalogue';
import { packHash } from '../src/lib/packs/hash';

const lit = (v: string) => `'${v.replaceAll("'", "''")}'`;

const out: string[] = [
  '-- Pack catalogue (docs/11), generated by scripts/packs-sql.ts. Idempotent.',
  'begin;',
];
for (const m of repoPacks()) {
  const json = JSON.stringify(m);
  if (json.includes('$manifest$')) throw new Error('manifest holds the quote tag');
  out.push(
    `insert into packs (key, version, title, description, manifest, hash) values (${lit(m.key)}, ${lit(m.version)}, ${lit(m.title)}, ${lit(m.description)}, $manifest$${json}$manifest$::jsonb, ${lit(packHash(m))}) on conflict (key, version) do nothing;`,
  );
}
out.push('commit;', '');
process.stdout.write(out.join('\n'));
